"""
Mock Shop API + minimal storefront
==================================

A tiny stand-in for a real e-commerce backend (Shopify, WooCommerce, ...)
plus a small shop website that displays the uploaded products.

Why a mock instead of a real shop?
- No account, no cost, always available for a demo.
- For the pipeline, a shop is "just an API": we POST product data with an
  API key and the shop stores it. That is exactly what this service does.
- The request body follows the shape of Shopify's Admin REST API
  ({"product": {"title", "body_html", "images": [{"src"}], "variants": [{"price", "sku"}]}}).
  Shopify would keep furniture details (dimensions, materials, ...) in
  "metafields"; here they are simple extra fields to keep the demo small.

Endpoints
- GET  /health                    -> liveness check (no auth)
- POST /products                  -> create or update a product (auth, upsert by SKU)
- GET  /products                  -> list all products (auth)
- GET  /products/{id}             -> one product (auth)
- GET  /api/storefront/products   -> PUBLIC read-only list for the website
- GET  /                          -> the shop website (static/index.html)
- GET  /media/...                 -> locally stored product images
- GET  /docs                      -> interactive API docs (generated by FastAPI)

Configuration (environment variables, never hard-coded):
- SHOP_API_KEY   (required) key clients must send in the X-API-Key header
- SHOP_DB_PATH   (optional) SQLite file, default: data/shop.db
- SHOP_MEDIA_DIR (optional) folder for downloaded images, default: data/media
- SHOP_CURRENCY  (optional) currency shown on the website, default: EUR
Test page (all optional; without CONTROL_PASSWORD the buttons are disabled):
- CONTROL_PASSWORD          demo password testers must enter
- CONTROL_COOLDOWN_SECONDS  wait time between two clicks of the same button (60)
- N8N_WEBHOOK_BASE          where n8n's webhooks are, e.g. http://host.docker.internal:5678/webhook
- SHEET_URL                 link to the Google Sheet (for the "open sheet" button)
- SUPPLIER_PUBLIC_URL       link to the supplier website for the browser
- VOICE_AGENT_ID            ElevenLabs agent id (not a secret)
"""

