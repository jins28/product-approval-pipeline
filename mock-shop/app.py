STATIC_DIR = Path(__file__).parent / "static"


# ---------------------------------------------------------------------------
# Configuration helpers
# (read at call time, so tests can change them with environment variables)
# ---------------------------------------------------------------------------

def db_path() -> str:
    return os.getenv("SHOP_DB_PATH", "data/shop.db")


def media_dir() -> str:
    return os.getenv("SHOP_MEDIA_DIR", "data/media")


def expected_api_key() -> str:
    key = os.getenv("SHOP_API_KEY")
    if not key:
        # Fail loudly instead of silently running an unprotected API.
        raise RuntimeError("SHOP_API_KEY is not set. Add it to your .env file.")
    return key


# ---------------------------------------------------------------------------
# Database (SQLite = one file, no extra server needed)
# ---------------------------------------------------------------------------

def get_conn() -> sqlite3.Connection:
    conn = sqlite3.connect(db_path())
    conn.row_factory = sqlite3.Row  # rows behave like dicts
    return conn


# Columns added after the first version. init_db() adds them to an existing
# database, so products you already uploaded are kept (a tiny "migration").
NEW_COLUMNS = {
    "images": "TEXT NOT NULL DEFAULT '[]'",          # JSON list of {"src", "alt"}
    "dimensions": "TEXT NOT NULL DEFAULT ''",
    "material_construction": "TEXT NOT NULL DEFAULT ''",
    "features_feel": "TEXT NOT NULL DEFAULT ''",
}


def init_db() -> None:
    os.makedirs(os.path.dirname(db_path()) or ".", exist_ok=True)
    with get_conn() as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS products (
                id           INTEGER PRIMARY KEY AUTOINCREMENT,
                sku          TEXT NOT NULL UNIQUE,   -- business key
                title        TEXT NOT NULL,
                body_html    TEXT NOT NULL,
                vendor       TEXT NOT NULL,
                product_type TEXT NOT NULL,
                price        TEXT NOT NULL,
                source_url   TEXT,
                created_at   TEXT NOT NULL,
                updated_at   TEXT NOT NULL
            )
            """
        )
        existing = {row["name"] for row in conn.execute("PRAGMA table_info(products)")}
        for column, definition in NEW_COLUMNS.items():
            if column not in existing:
                conn.execute(f"ALTER TABLE products ADD COLUMN {column} {definition}")


@asynccontextmanager
async def lifespan(app: FastAPI):
    expected_api_key()  # crash on startup if the key is missing
    init_db()
    yield


app = FastAPI(title="Mock Shop API", version="1.1.0", lifespan=lifespan)

# Product images that the scraper downloads are served from /media/...
os.makedirs(media_dir(), exist_ok=True)
app.mount("/media", StaticFiles(directory=media_dir()), name="media")
# CSS and JavaScript of the website
app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")


# ---------------------------------------------------------------------------
# Request models (Pydantic validates incoming JSON for us)
# ---------------------------------------------------------------------------

class Variant(BaseModel):
    sku: str = Field(..., min_length=1, examples=["SOFA-001"])
    # Shopify sends prices as strings like "2490.00" -> same here.
    price: str = Field(..., pattern=r"^\d+(\.\d{1,2})?$", examples=["2490.00"])


class Image(BaseModel):
    # Either a full URL (https://...) or a local path like /media/sofa-1.jpg
    src: str = Field(..., min_length=1, examples=["/media/sofa-001-1.jpg"])
    alt: str = ""


class ProductIn(BaseModel):
    title: str = Field(..., min_length=1)
    body_html: str = ""
    vendor: str = "Demo Supplier"
    product_type: str = "Sofa"
    source_url: str | None = None
    images: list[Image] = []
    dimensions: str = ""
    material_construction: str = ""
    features_feel: str = ""
    variants: list[Variant] = Field(..., min_length=1)


class ProductEnvelope(BaseModel):
    """Shopify wraps the product in a "product" key; we do the same."""
    product: ProductIn


# ---------------------------------------------------------------------------
# Auth: every write/read endpoint of the API requires the X-API-Key header
# ---------------------------------------------------------------------------

# Declaring the key as a security scheme makes the "Authorize" button appear
# on the /docs page, so you can test the API in the browser.
api_key_header = APIKeyHeader(name="X-API-Key", auto_error=False)


def require_api_key(x_api_key: str | None = Depends(api_key_header)) -> None:
    # compare_digest avoids timing attacks (good habit, cheap to do)
    if not x_api_key or not secrets.compare_digest(x_api_key, expected_api_key()):
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED,
                            detail="Missing or invalid X-API-Key header")


def row_to_product(row: sqlite3.Row) -> dict:
    """Return products in the same shape they were sent in."""
    return {
        "id": row["id"],
        "title": row["title"],
        "body_html": row["body_html"],
        "vendor": row["vendor"],
        "product_type": row["product_type"],
        "source_url": row["source_url"],
        "images": json.loads(row["images"]),
        "dimensions": row["dimensions"],
        "material_construction": row["material_construction"],
        "features_feel": row["features_feel"],
        "variants": [{"sku": row["sku"], "price": row["price"]}],
        "created_at": row["created_at"],
        "updated_at": row["updated_at"],
    }


def html_to_text(value: str) -> str:
    """
    Turn HTML into plain text for the website.
    Line breaks are kept, all tags are removed. The browser then shows it
    with textContent, so scraped HTML can never run scripts on our page.
    """
    value = re.sub(r"(?i)<br\s*/?>|</p>|</li>|</h\d>", "\n", value or "")
    value = re.sub(r"<[^>]+>", "", value)
    value = html.unescape(value)
    lines = [line.strip() for line in value.splitlines()]
    return "\n".join(line for line in lines if line)


