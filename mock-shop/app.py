# ---------------------------------------------------------------------------
# Test page ("Steuerung"): buttons that start the n8n workflows
# ---------------------------------------------------------------------------
#
# The browser never talks to n8n directly. It calls these endpoints, and the
# shop's backend forwards the click to n8n's webhook. So n8n does not need to
# be reachable from the internet; only the shop does.
# Protection: a demo password + a cooldown per button (costs and abuse).

_last_run: dict[str, float] = {}


def control_settings() -> dict:
    return {
        "password": os.getenv("CONTROL_PASSWORD", ""),
        "cooldown": int(os.getenv("CONTROL_COOLDOWN_SECONDS", "60")),
        "n8n": os.getenv("N8N_WEBHOOK_BASE", "http://host.docker.internal:5678/webhook").rstrip("/"),
    }


class CheckRequest(BaseModel):
    password: str
    limit: int = Field(3, ge=1, le=10)
    collection: Literal["all", "sofa", "chair"] = "all"


class UploadRequest(BaseModel):
    password: str


def start_workflow(action: str, webhook_path: str, password: str, body: dict) -> dict:
    settings = control_settings()
    if not settings["password"]:
        raise HTTPException(503, "Die Testseite ist noch nicht eingerichtet (CONTROL_PASSWORD fehlt).")
    if not secrets.compare_digest(password.encode(), settings["password"].encode()):
        time.sleep(1)  # slows down password guessing
        raise HTTPException(401, "Falsches Demo-Passwort.")

    wait = settings["cooldown"] - (time.monotonic() - _last_run.get(action, -1e12))
    if wait > 0:
        seconds = math.ceil(wait)
        raise HTTPException(429, f"Bitte noch {seconds} Sekunden warten.", headers={"Retry-After": str(seconds)})

    request = urllib.request.Request(
        f"{settings['n8n']}/{webhook_path}",
        data=json.dumps(body).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=15):
            pass
    except urllib.error.HTTPError as err:
        if err.code == 404:
            raise HTTPException(502, "Der Workflow ist nicht aktiv (Webhook nicht gefunden). "
                                     "Bitte in n8n veröffentlichen/aktivieren.") from err
        raise HTTPException(502, f"n8n hat mit Fehler {err.code} geantwortet.") from err
    except (urllib.error.URLError, OSError) as err:
        raise HTTPException(502, "n8n ist nicht erreichbar. Läuft n8n?") from err

    _last_run[action] = time.monotonic()
    return {"status": "started"}


@app.get("/api/control/config")
def control_config() -> dict:
    """Public settings the test page needs (no secrets in here)."""
    with get_conn() as conn:
        count = conn.execute("SELECT COUNT(*) FROM products").fetchone()[0]
    return {
        "enabled": bool(control_settings()["password"]),
        "cooldown": control_settings()["cooldown"],
        "sheet_url": os.getenv("SHEET_URL", ""),
        "supplier_url": os.getenv("SUPPLIER_PUBLIC_URL", "http://localhost:8003"),
        "voice_agent_id": os.getenv("VOICE_AGENT_ID", ""),
        "shop_product_count": count,
    }


@app.post("/api/control/check-new-products")
def control_check(req: CheckRequest) -> dict:
    return start_workflow("check", "check-new-products", req.password,
                          {"limit": req.limit, "collection": req.collection})


@app.post("/api/control/upload-approved")
def control_upload(req: UploadRequest) -> dict:
    return start_workflow("upload", "upload-approved", req.password, {})


@app.get("/steuerung", include_in_schema=False)
def control_page() -> FileResponse:
    return FileResponse(STATIC_DIR / "steuerung.html")
