@app.get("/health")
def health() -> dict:
    return {"status": "ok"}


@app.post("/products", dependencies=[Depends(require_api_key)])
def upsert_product(payload: ProductEnvelope, response: Response) -> dict:
    """
    Create a product, or update it if the SKU already exists ("upsert").

    Why upsert? If n8n retries an upload after a timeout, we must not create
    the same product twice. Using the SKU as the unique key makes the call
    idempotent: sending it twice gives the same result as sending it once.
    """
    p = payload.product
    v = p.variants[0]  # one variant per product keeps the demo simple
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    images = json.dumps([img.model_dump() for img in p.images], ensure_ascii=False)
    fields = (p.title, p.body_html, p.vendor, p.product_type, v.price, p.source_url,
              images, p.dimensions, p.material_construction, p.features_feel)

    with get_conn() as conn:
        existing = conn.execute("SELECT id FROM products WHERE sku = ?", (v.sku,)).fetchone()
        if existing:
            conn.execute(
                """UPDATE products SET title=?, body_html=?, vendor=?, product_type=?,
                       price=?, source_url=?, images=?, dimensions=?,
                       material_construction=?, features_feel=?, updated_at=?
                   WHERE sku=?""",
                (*fields, now, v.sku),
            )
            response.status_code = status.HTTP_200_OK
            product_id = existing["id"]
        else:
            cur = conn.execute(
                """INSERT INTO products (title, body_html, vendor, product_type, price,
                       source_url, images, dimensions, material_construction,
                       features_feel, sku, created_at, updated_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (*fields, v.sku, now, now),
            )
            response.status_code = status.HTTP_201_CREATED
            product_id = cur.lastrowid

        row = conn.execute("SELECT * FROM products WHERE id = ?", (product_id,)).fetchone()
    return {"product": row_to_product(row)}


@app.get("/products", dependencies=[Depends(require_api_key)])
def list_products() -> dict:
    with get_conn() as conn:
        rows = conn.execute("SELECT * FROM products ORDER BY id").fetchall()
    return {"products": [row_to_product(r) for r in rows]}


@app.get("/products/{product_id}", dependencies=[Depends(require_api_key)])
def get_product(product_id: int) -> dict:
    with get_conn() as conn:
        row = conn.execute("SELECT * FROM products WHERE id = ?", (product_id,)).fetchone()
    if row is None:
        raise HTTPException(status_code=404, detail="Product not found")
    return {"product": row_to_product(row)}


