@app.get("/api/storefront/products")
def storefront_products() -> dict:
    """
    Public, read-only product list for the website.
    No API key needed (a shop window is public), but it can only READ.
    Only the fields the website needs are returned, as plain text.
    """
    with get_conn() as conn:
        rows = conn.execute("SELECT * FROM products ORDER BY id DESC").fetchall()
    return {
        "currency": os.getenv("SHOP_CURRENCY", "EUR"),
        "products": [
            {
                "id": r["id"],
                "title": r["title"],
                "product_type": r["product_type"],
                "price": r["price"],
                "description": html_to_text(r["body_html"]),
                "dimensions": html_to_text(r["dimensions"]),
                "material_construction": html_to_text(r["material_construction"]),
                "features_feel": html_to_text(r["features_feel"]),
                "images": json.loads(r["images"]),
                "created_at": r["created_at"],
            }
            for r in rows
        ],
    }


